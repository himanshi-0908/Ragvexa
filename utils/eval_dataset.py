"""
eval_dataset.py — Synthetic Evaluation Dataset Generator

Generates and persists synthetic query → chunk_id pairs during ingestion.
Call generate_eval_dataset() once per ingested document.
During benchmark runs, call load_eval_queries() to read from DB only.

This is a SYNTHETIC dataset generated by an LLM — NOT human-labeled ground truth.
Its purpose is to enable reproducible pipeline comparisons, not absolute accuracy claims.
"""

import hashlib
from typing import List, Dict

from utils.database import SessionLocal, SyntheticEvalItem
from llm.llm_handler import get_llm


def _file_hash(file_path: str) -> str:
    """Compute MD5 of a file's contents for deduplication."""
    h = hashlib.md5()
    try:
        with open(file_path, "rb") as f:
            for chunk in iter(lambda: f.read(8192), b""):
                h.update(chunk)
    except Exception:
        h.update(file_path.encode())
    return h.hexdigest()


def _content_hash(text: str) -> str:
    return hashlib.md5(text.encode()).hexdigest()


def dataset_exists_for_doc(user_id: int, doc_hash: str) -> bool:
    """Return True if synthetic eval data already exists for this document."""
    db = SessionLocal()
    try:
        count = (
            db.query(SyntheticEvalItem)
            .filter(
                SyntheticEvalItem.user_id == user_id,
                SyntheticEvalItem.doc_hash == doc_hash,
            )
            .count()
        )
        return count > 0
    finally:
        db.close()


def generate_eval_dataset(
    chunks,
    user_id: int,
    source_name: str,
    doc_hash: str,
    questions_per_chunk: int = 2,
    max_chunks: int = 30,
) -> int:
    """
    Generate synthetic evaluation queries for each chunk and persist to DB.
    Returns the number of query-chunk pairs saved.

    Args:
        chunks: list of LangChain Document objects (already ingested)
        user_id: authenticated user's DB id
        source_name: filename of the ingested document
        doc_hash: MD5 hash of the source file for deduplication
        questions_per_chunk: how many questions to generate per chunk (default 2)
        max_chunks: cap to avoid excessive LLM calls on very large docs (default 30)
    """
    if dataset_exists_for_doc(user_id, doc_hash):
        return 0  # Already generated, skip

    llm = get_llm()
    db = SessionLocal()
    saved = 0

    try:
        sample_chunks = chunks[:max_chunks]
        for chunk in sample_chunks:
            chunk_id = chunk.metadata.get("chunk_id", _content_hash(chunk.page_content)[:12])
            text = chunk.page_content.strip()
            if len(text) < 80:
                continue  # skip trivially short chunks

            prompt = (
                f"Read the following passage and generate exactly {questions_per_chunk} "
                "distinct, specific natural language questions that a user would ask "
                "whose answer is DIRECTLY contained in this passage.\n"
                "Return ONLY the questions, one per line, no numbering, no preamble.\n\n"
                f"Passage:\n{text[:1200]}\n\nQuestions:"
            )
            try:
                response = llm.invoke(prompt)
                questions = [
                    q.strip()
                    for q in response.content.strip().split("\n")
                    if q.strip() and len(q.strip()) > 10
                ][:questions_per_chunk]
            except Exception:
                continue

            for q in questions:
                item = SyntheticEvalItem(
                    user_id=user_id,
                    query_text=q,
                    chunk_id=chunk_id,
                    source_doc=source_name,
                    doc_hash=doc_hash,
                )
                db.add(item)
                saved += 1

        db.commit()
    except Exception:
        db.rollback()
    finally:
        db.close()

    return saved


def load_eval_queries(user_id: int, limit: int = 50) -> List[Dict]:
    """
    Load persisted synthetic eval queries from DB for a given user.
    Returns list of dicts with query_text and relevant_chunk_ids.
    """
    db = SessionLocal()
    try:
        items = (
            db.query(SyntheticEvalItem)
            .filter(SyntheticEvalItem.user_id == user_id)
            .order_by(SyntheticEvalItem.created_at.desc())
            .limit(limit)
            .all()
        )
        # Group by query_text so one query can map to multiple relevant chunks
        query_map: Dict[str, Dict] = {}
        for item in items:
            if item.query_text not in query_map:
                query_map[item.query_text] = {
                    "query": item.query_text,
                    "relevant_chunk_ids": [],
                    "source_doc": item.source_doc,
                }
            query_map[item.query_text]["relevant_chunk_ids"].append(item.chunk_id)
        return list(query_map.values())
    finally:
        db.close()


def get_eval_dataset_stats(user_id: int) -> Dict:
    """Return stats about the synthetic eval dataset for UI display."""
    db = SessionLocal()
    try:
        items = (
            db.query(SyntheticEvalItem)
            .filter(SyntheticEvalItem.user_id == user_id)
            .all()
        )
        sources: Dict[str, int] = {}
        for item in items:
            sources[item.source_doc] = sources.get(item.source_doc, 0) + 1
        return {
            "total_queries": len(items),
            "unique_queries": len({i.query_text for i in items}),
            "sources": sources,
        }
    finally:
        db.close()
